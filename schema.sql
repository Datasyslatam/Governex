	VERSION VARCHAR(10) NOT NULL,
	DESCRIPCION TEXT,
	ARCHIVO_URL TEXT,
	HASH_SHA256 TEXT,
	AUTOR_ID INTEGER REFERENCES USUARIOS (ID),
	FECHA TIMESTAMPTZ NOT NULL DEFAULT NOW()
