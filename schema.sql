CREATE TABLE EVALUACIONES_COMPETENCIA (
	ID SERIAL PRIMARY KEY,
	PERSONAL_ID INTEGER NOT NULL REFERENCES PERSONAL (ID),
	BRECHA_PCT INTEGER NOT NULL DEFAULT 0 CHECK (BRECHA_PCT BETWEEN 0 AND 100),
