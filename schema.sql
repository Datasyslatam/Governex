CREATE TABLE DOCUMENTO_APROBACIONES (
	ID SERIAL PRIMARY KEY,
	DOCUMENTO_ID INTEGER NOT NULL REFERENCES DOCUMENTOS (ID),
	APROBADOR_ID INTEGER NOT NULL REFERENCES USUARIOS (ID),
