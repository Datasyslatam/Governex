CREATE TABLE PERSONAL (
	ID SERIAL PRIMARY KEY,
	NOMBRE VARCHAR(100) NOT NULL,
	CARGO VARCHAR(100),
	PROCESO_ID INTEGER REFERENCES PROCESOS (ID),
