CREATE TABLE DOCUMENTOS (
	ID SERIAL PRIMARY KEY,
	CODIGO VARCHAR(20) NOT NULL UNIQUE,
	TITULO VARCHAR(200) NOT NULL,
	TIPO VARCHAR(20) NOT NULL CHECK (
		TIPO IN (
			'Manual',
			'Política',
