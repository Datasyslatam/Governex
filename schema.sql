CREATE TABLE PROVEEDORES (
	ID SERIAL PRIMARY KEY,
	NIT VARCHAR(30) NOT NULL UNIQUE,
	RAZON VARCHAR(200) NOT NULL,
	TIPO VARCHAR(50),
